// A message long enough to cross the block buffer several times, so the
// streaming path is checked against the one-shot path rather than only
// against a single compression.
static int stream_matches(const u8 *message, u32 length, u32 chunk) {
    u8 one_shot[BLAKE2B_OUT_MAX];
    u8 streamed[BLAKE2B_OUT_MAX];
    struct blake2b_state state;
    if (blake2b(one_shot, BLAKE2B_OUT_MAX, message, length)) return 0;
    if (blake2b_init(&state, BLAKE2B_OUT_MAX, 0, 0)) return 0;
    for (u32 offset = 0; offset < length; offset += chunk) {
        u32 take = length - offset < chunk ? length - offset : chunk;
        if (blake2b_update(&state, message + offset, take)) return 0;
    }
    if (blake2b_final(&state, streamed, BLAKE2B_OUT_MAX)) return 0;
    return crypto_equal(one_shot, streamed, BLAKE2B_OUT_MAX);
}

static int matches(const u8 *message, u32 length, const u8 *key, u32 keylen,
                   const u8 *expected, u32 outlen) {
    struct blake2b_state state;
    u8 digest[BLAKE2B_OUT_MAX];
    if (blake2b_init(&state, outlen, key, keylen)) return 0;
    if (blake2b_update(&state, message, length)) return 0;
    if (blake2b_final(&state, digest, outlen)) return 0;
    return crypto_equal(digest, expected, outlen);
}

int test_blake2b64(void) {
    static u8 message[256];
    for (u32 index = 0; index < 256; index++) message[index] = (u8)index;

    int valid = 1;
    valid = valid && matches(message, 0, 0, 0, digest_empty, 64);
    valid = valid && matches((const u8 *)"abc", 3, 0, 0, digest_abc, 64);
    valid = valid && matches((const u8 *)"abc", 3, 0, 0, digest_abc32, 32);
    valid = valid &&
        matches((const u8 *)"The quick brown fox jumps over the lazy dog", 43,
                0, 0, digest_fox, 64);
    valid = valid && matches(message, 128, 0, 0, digest_block128, 64);
    valid = valid && matches(message, 129, 0, 0, digest_block129, 64);
    valid = valid && matches(message, 256, 0, 0, digest_bytes256, 64);

    u8 key[BLAKE2B_KEY_MAX];
    for (u32 index = 0; index < BLAKE2B_KEY_MAX; index++)
        key[index] = (u8)index;
    valid = valid &&
        matches((const u8 *)"abc", 3, key, BLAKE2B_KEY_MAX, digest_keyed, 64);
    u8 short_key = 0;
    valid = valid &&
        matches(message, 0, &short_key, 1, digest_keyed1, 64);

    // Chunk sizes that straddle the block boundary exercise the deferred
    // compression in update; a chunk of exactly 128 and one of 127 take
    // different paths through it.
    for (u32 chunk = 1; chunk <= 256 && valid; chunk++)
        valid = stream_matches(message, 256, chunk);

    // A digest length the caller never asked for must be refused, or a caller
    // that mixed up two lengths silently gets a truncated hash.
    struct blake2b_state state;
    u8 digest[BLAKE2B_OUT_MAX];
    valid = valid && !blake2b_init(&state, 32, 0, 0);
    valid = valid && blake2b_final(&state, digest, 64) != 0;

    return valid ? 0 : -1;
}
